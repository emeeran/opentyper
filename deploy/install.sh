#!/usr/bin/env bash
# OpenTyper installer for Ubuntu 26.04 LTS (x86_64).
# Idempotent: safe to re-run; existing data is never overwritten or deleted.
# Supports --dry-run.
#
# Usage: sudo ./install.sh [--dry-run] [--app-dir /opt/opentyper]
set -euo pipefail

APP_DIR="/opt/opentyper"
APP_USER="opentyper"
APP_GROUP="${APP_USER}"
BIND_HOST="127.0.0.1"
BIND_PORT="8000"
LOG_DIR="/var/log/opentyper"

DRY_RUN=0
log() { echo "[install] $*"; }
die() { echo "[install] ERROR: $*" >&2; exit 1; }

while [[ $# -gt 0 ]]; do
  case "$1" in
    --dry-run) DRY_RUN=1 ;;
    --app-dir) APP_DIR="$2"; shift ;;
    *) die "unknown argument: $1" ;;
  esac
  shift
done

# dry-run makes no changes, so it may run unprivileged
[[ $EUID -eq 0 || $DRY_RUN -eq 1 ]] || die "run as root (sudo)"

# resolve the directory containing this script (the source tree)
SRC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
[[ -f "${SRC_DIR}/app/main.py" ]] || die "source tree not found at ${SRC_DIR}"
[[ -f "${SRC_DIR}/pyproject.toml" ]] || die "pyproject.toml not found at ${SRC_DIR}"

run() {
  if [[ $DRY_RUN -eq 1 ]]; then log "DRY-RUN: $*"; else "$@"; fi
}

log "plan:"
log "  source:    ${SRC_DIR}"
log "  app dir:   ${APP_DIR}"
log "  user:      ${APP_USER}"
log "  bind:      ${BIND_HOST}:${BIND_PORT}"
log "  log dir:   ${LOG_DIR}"
[[ $DRY_RUN -eq 1 ]] && log "  mode:      DRY-RUN (no changes)"

# 1. install uv if missing
if ! command -v uv >/dev/null 2>&1; then
  log "uv not found — installing"
  run curl -LsSf https://astral.sh/uv/install.sh | run_env=1 sh
  export PATH="$HOME/.local/bin:$PATH"
  command -v uv >/dev/null 2>&1 || die "uv installation failed"
fi
command -v uv >/dev/null 2>&1 || die "uv still not on PATH after install attempt"
log "uv: $(uv --version)"

# 2. dedicated system user
if id "${APP_USER}" >/dev/null 2>&1; then
  log "user ${APP_USER} exists"
else
  log "creating system user ${APP_USER}"
  run useradd --system --shell /usr/sbin/nologin --home "${APP_DIR}" "${APP_USER}"
fi

# 3. app directory — copy source tree (rsync keeps data/ intact)
log "syncing source to ${APP_DIR}"
if [[ $DRY_RUN -eq 1 ]]; then
  log "DRY-RUN: rsync -a --delete --exclude data --exclude .venv --exclude logs '${SRC_DIR}/' '${APP_DIR}/'"
else
  mkdir -p "${APP_DIR}"
  rsync -a --delete \
    --exclude "data/" --exclude ".venv/" --exclude ".uv-python/" \
    --exclude "logs/" --exclude "__pycache__/" \
    "${SRC_DIR}/" "${APP_DIR}/"
fi

# 4. data + logs dirs with correct ownership
log "creating ${APP_DIR}/data and ${LOG_DIR}"
run mkdir -p "${APP_DIR}/data" "${LOG_DIR}"
run chown -R "${APP_USER}:${APP_GROUP}" "${APP_DIR}/data" "${LOG_DIR}"
run chmod 700 "${APP_DIR}/data"

if [[ $DRY_RUN -eq 0 ]]; then
  # keep uv-managed interpreters inside the app dir: under ProtectHome=true the
  # service user cannot traverse /root/.local (uv's default install location)
  VENV_PY="${APP_DIR}/.venv/bin/python"
  if [[ -L "$VENV_PY" ]]; then
    target="$(readlink -f "$VENV_PY")"
    case "$target" in
      "${APP_DIR}"/*) ;;
      *) log "venv interpreter lives outside app dir ($target) — recreating venv"
         rm -rf "${APP_DIR}/.venv" "${APP_DIR}/.uv-python" ;;
    esac
  fi
  log "installing python dependencies (uv sync)"
  export UV_PYTHON_INSTALL_DIR="${APP_DIR}/.uv-python"
  (cd "${APP_DIR}" && uv sync --no-dev)
  chown -R "${APP_USER}:${APP_GROUP}" "${APP_DIR}/.venv" "${APP_DIR}/.uv-python"
fi

# 5. systemd unit (hardened)
UNIT=/etc/systemd/system/opentyper.service
log "writing ${UNIT}"
if [[ $DRY_RUN -eq 1 ]]; then
  log "DRY-RUN: write unit file with Environment=OPENTYPER_DATA_DIR=${APP_DIR}/data, ExecStart=${APP_DIR}/.venv/bin/uvicorn app.main:app --host ${BIND_HOST} --port ${BIND_PORT}"
else
  cat > "${UNIT}" <<EOF
# OpenTyper systemd unit (generated by deploy/install.sh)
[Unit]
Description=OpenTyper - self-hosted BYOK chat UI
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=${APP_USER}
Group=${APP_GROUP}
WorkingDirectory=${APP_DIR}
Environment=OPENTYPER_DATA_DIR=${APP_DIR}/data
ExecStart=${APP_DIR}/.venv/bin/uvicorn app.main:app --host ${BIND_HOST} --port ${BIND_PORT}
Restart=on-failure
RestartSec=3

# hardening
NoNewPrivileges=true
ProtectSystem=strict
ProtectHome=true
PrivateTmp=true
ReadWritePaths=${APP_DIR}/data ${LOG_DIR}
ProtectKernelTunables=true
ProtectKernelModules=true
ProtectControlGroups=true
RestrictSUIDSGID=true
LockPersonality=true
MemoryDenyWriteExecute=true
RestrictNamespaces=true
SystemCallArchitectures=native
CapabilityBoundingSet=
AmbientCapabilities=

[Install]
WantedBy=multi-user.target
EOF
fi

# 5b. the venv was created by root — hand it to the service user so runtime
#     tooling can read/execute it under ProtectSystem=strict
if [[ $DRY_RUN -eq 0 ]]; then
  chown -R "${APP_USER}:${APP_GROUP}" "${APP_DIR}/.venv"
fi

log "enabling service"
run systemctl daemon-reload
run systemctl enable --now opentyper.service

if [[ $DRY_RUN -eq 0 ]]; then
  sleep 2
  if systemctl is-active --quiet opentyper.service; then
    log "service is active"
  else
    log "WARNING: service not active — check: journalctl -u opentyper -n 50"
  fi
  for i in $(seq 1 10); do
    curl -fsS "http://${BIND_HOST}:${BIND_PORT}/api/health" >/dev/null 2>&1 && {
      log "health check OK: http://${BIND_HOST}:${BIND_PORT}/api/health"; break; }
    sleep 1
    [[ $i -eq 10 ]] && log "WARNING: health endpoint not responding yet"
  done
fi

log "done."
[[ $DRY_RUN -eq 1 ]] && log "dry-run complete — nothing was changed."
